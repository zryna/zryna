//! Explicit test-only bounded trace protocol; no imports or memory exports.
use super::{BYTE, Body, Diagnostic, FunctionCode, I, Model, WORD};
use wasm_encoder::BlockType;
pub(super) fn getter(m: &Model<'_, '_, '_>) -> Result<FunctionCode, Diagnostic> {
    let mut b = Body::new(m, 1)?;
    b.ops([
        I::LocalGet(0),
        I::I32Eqz,
        I::If(BlockType::Empty),
        I::GlobalGet(1),
        I::Return,
        I::End,
    ])?;
    configure(&mut b)?;
    b.ops([
        I::LocalGet(0),
        I::I32Const(0x4000_0000),
        I::I32Eq,
        I::If(BlockType::Empty),
        I::GlobalGet(9),
        I::Return,
        I::End,
    ])?;
    b.ops([
        I::LocalGet(0),
        I::I32Const(0x4000_0000),
        I::I32Sub,
        I::LocalTee(1),
        I::I32Const(1),
        I::I32LtU,
        I::LocalGet(1),
        I::GlobalGet(9),
        I::I32GtU,
        I::I32Or,
        I::LocalGet(1),
        I::I32Const(4096),
        I::I32GtU,
        I::I32Or,
        I::If(BlockType::Empty),
        I::Unreachable,
        I::End,
    ])?;
    b.ops([
        I::I32Const(
            crate::generic_execution_v1::checked_u32(m.memory.claims().trace_start)?.cast_signed(),
        ),
        I::LocalGet(1),
        I::I32Const(1),
        I::I32Sub,
        I::I32Const(4),
        I::I32Mul,
        I::I32Add,
        I::I32Load(WORD),
    ])?;
    FunctionCode::new(1, 1, 1, b)
}
pub(super) fn recorder(m: &Model<'_, '_, '_>) -> Result<FunctionCode, Diagnostic> {
    let mut b = Body::new(m, 2)?;
    b.ops([
        I::GlobalGet(9),
        I::I32Const(4096),
        I::I32GtU,
        I::If(BlockType::Empty),
        I::Return,
        I::End,
    ])?;
    b.ops([
        I::LocalGet(4),
        I::I32Const(4091),
        I::I32GtU,
        I::GlobalGet(9),
        I::LocalGet(4),
        I::I32Const(5),
        I::I32Add,
        I::I32Add,
        I::I32Const(4096),
        I::I32GtU,
        I::I32Or,
        I::If(BlockType::Empty),
        I::I32Const(4097),
        I::GlobalSet(9),
        I::Return,
        I::End,
    ])?;
    b.ops([
        I::I32Const(
            crate::generic_execution_v1::checked_u32(m.memory.claims().trace_start)?.cast_signed(),
        ),
        I::GlobalGet(9),
        I::I32Const(4),
        I::I32Mul,
        I::I32Add,
        I::LocalSet(6),
    ])?;
    for local in 0..5 {
        b.ops([
            I::LocalGet(6),
            I::LocalGet(local),
            I::I32Store(wasm_encoder::MemArg { offset: u64::from(local * 4), ..WORD }),
        ])?;
    }
    b.ops([
        I::Block(BlockType::Empty),
        I::Loop(BlockType::Empty),
        I::LocalGet(7),
        I::LocalGet(4),
        I::I32GeU,
        I::BrIf(1),
        I::LocalGet(6),
        I::I32Const(20),
        I::I32Add,
        I::LocalGet(7),
        I::I32Const(4),
        I::I32Mul,
        I::I32Add,
        I::LocalGet(5),
        I::LocalGet(7),
        I::I32Add,
        I::I32Load8U(BYTE),
        I::I32Store(WORD),
        I::LocalGet(7),
        I::I32Const(1),
        I::I32Add,
        I::LocalSet(7),
        I::Br(0),
        I::End,
        I::End,
        I::GlobalGet(9),
        I::LocalGet(4),
        I::I32Const(5),
        I::I32Add,
        I::I32Add,
        I::GlobalSet(9),
    ])?;
    FunctionCode::new(6, 0, 2, b)
}

fn configure(b: &mut Body<'_>) -> Result<(), Diagnostic> {
    b.ops([
        I::LocalGet(0),
        I::I32Const(crate::generic_execution_v1::checked_u32(0xf000_0000_u32)?.cast_signed()),
        I::I32And,
        I::I32Const(0x2000_0000),
        I::I32Eq,
        I::If(BlockType::Empty),
    ])?;
    b.ops([
        I::GlobalGet(8),
        I::GlobalGet(2),
        I::I32Or,
        I::If(BlockType::Empty),
        I::Unreachable,
        I::End,
    ])?;
    b.ops([
        I::LocalGet(0),
        I::I32Const(24),
        I::I32ShrU,
        I::I32Const(15),
        I::I32And,
        I::LocalTee(1),
        I::I32Eqz,
        I::LocalGet(1),
        I::I32Const(2),
        I::I32Eq,
        I::I32Or,
        I::LocalGet(1),
        I::I32Const(6),
        I::I32Eq,
        I::I32Or,
        I::I32Eqz,
        I::If(BlockType::Empty),
        I::Unreachable,
        I::End,
    ])?;
    b.ops([
        I::LocalGet(0),
        I::I32Const(0x00ff_ffff),
        I::I32And,
        I::I32Eqz,
        I::LocalGet(1),
        I::I32Eqz,
        I::LocalGet(0),
        I::I32Const(0x2000_0001),
        I::I32Ne,
        I::I32And,
        I::I32Or,
        I::If(BlockType::Empty),
        I::Unreachable,
        I::End,
    ])?;
    b.ops([
        I::LocalGet(1),
        I::GlobalSet(3),
        I::LocalGet(0),
        I::I32Const(0x00ff_ffff),
        I::I32And,
        I::GlobalSet(4),
        I::I32Const(0),
        I::Return,
        I::End,
    ])?;
    Ok(())
}
