//! Fixed C linker output through the existing atomic data publisher; no executable grant.
use super::super::super::{CapturedForeignLibrary, CompiledObject, Failure, Observation, observe};
use super::Fixture;
use crate::javascript::publish_complete_artifact;
use std::{fs, os::unix::fs::PermissionsExt as _};

fn linked(
    fixture: &Fixture,
    library: &CapturedForeignLibrary,
    foreign: &CompiledObject,
    client: &[u8],
) -> Result<Observation, Failure> {
    observe(
        &fixture.root,
        &fixture.requirements,
        library,
        foreign,
        client,
        Some(&fixture.runtime),
        false,
    )
}

fn unchanged(fixture: &Fixture, bytes: &[u8]) {
    let root = fixture.root.path();
    assert_eq!(fs::read(root.join("ffi-result.elf")).expect("exact prior artifact"), bytes);
    assert_eq!(
        fs::read_dir(root)
            .expect("closed output inventory")
            .map(|entry| { entry.expect("regular output entry").file_name() })
            .collect::<Vec<_>>(),
        [std::ffi::OsString::from("ffi-result.elf")]
    );
}

#[test]
fn linked_c_result_publishes_atomically_and_preserves_prior_state_on_rejection() {
    let fixture = Fixture::new();
    let (library, foreign) = fixture.foreign();
    let original = linked(&fixture, &library, &foreign, b"int main(void){return 0;}")
        .expect("actual original generated byte object, C library and private runtime link");
    fixture.empty();
    original.library.check_binding(&fixture.requirements).expect("original source issuer");
    assert_eq!(original.requirements.object_sha256(), fixture.requirements.object_sha256());
    let published = publish_complete_artifact(
        &original.final_elf,
        &fixture.root,
        "ffi-result",
        "elf",
        "fixed C fixture data",
    )
    .expect("existing atomic create-only publisher");
    assert!(published.diagnostics.is_empty());
    assert_eq!(published.path, fixture.root.path().join("ffi-result.elf"));
    assert_eq!(
        fs::metadata(&published.path).expect("data permissions").permissions().mode() & 0o111,
        0
    );
    unchanged(&fixture, &original.final_elf);
    let Err(collision) = publish_complete_artifact(
        b"collision must not replace the linked artifact",
        &fixture.root,
        "ffi-result",
        "elf",
        "fixed C fixture data",
    ) else {
        panic!("existing destination must reject before replacement");
    };
    assert_eq!(collision.code(), "ZRYNA-D2007");
    unchanged(&fixture, &original.final_elf);
    let mut substituted = fixture.runtime.clone();
    substituted.source[0] ^= 1;
    let rejected = observe(
        &fixture.root,
        &fixture.requirements,
        &library,
        &foreign,
        b"not C",
        Some(&substituted),
        false,
    )
    .expect_err("changed original runtime source rejects before new compiler/linker");
    assert_eq!(rejected.diagnostics[0].code(), "ZRYNA-C4102");
    assert!(rejected.invocations.is_empty());
    unchanged(&fixture, &original.final_elf);
    let failed = linked(
        &fixture,
        &library,
        &foreign,
        b"extern void missing(void); int main(void){missing();return 0;}",
    )
    .expect_err("actual unresolved-symbol linker failure");
    assert_eq!(failed.comparator_stage, Some("link-process"));
    assert!(failed.final_elf.is_none());
    assert!(
        failed.invocations.iter().any(|call| !call.status.success() && !call.stderr.is_empty())
    );
    unchanged(&fixture, &original.final_elf);
    let recovered = linked(&fixture, &library, &foreign, b"int main(void){return 0;}")
        .expect("fresh pristine link after both real rejections");
    unchanged(&fixture, &original.final_elf);
    let second = publish_complete_artifact(
        &recovered.final_elf,
        &fixture.root,
        "ffi-recovery",
        "elf",
        "fixed C fixture data",
    )
    .expect("fresh exact publication after linker recovery");
    assert!(second.diagnostics.is_empty());
    assert_eq!(fs::read(&second.path).expect("exact recovered artifact"), recovered.final_elf);
    for observation in [&original, &recovered] {
        let report = observation.report();
        for flag in ["execution_authorized", "target_executed", "driver_executable_mode_applied"] {
            assert_eq!(report[flag], false);
        }
    }
    fs::remove_file(second.path).expect("remove only own data artifact");
    unchanged(&fixture, &original.final_elf);
    fs::remove_file(published.path).expect("remove only own original data artifact");
    fixture.empty();
}
