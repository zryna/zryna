// Explicitly HOSTILE structural counterfactual bytes, not additional compiler observations.
fn put(bytes: &mut [u8], offset: usize, value: u64, width: usize) {
    bytes[offset..offset + width].copy_from_slice(&value.to_le_bytes()[..width]);
}
fn string(strings: &mut Vec<u8>, text: &str) -> u64 {
    let offset = u64::try_from(strings.len()).expect("small control strings");
    strings.extend_from_slice(text.as_bytes());
    strings.push(0);
    offset
}
fn align(bytes: &mut Vec<u8>, alignment: usize) {
    let missing = (alignment - bytes.len() % alignment) % alignment;
    bytes.resize(bytes.len() + missing, 0);
}
